package com.rojo.app.ui.features

import android.content.Context
import com.rojo.app.models.Project
import com.rojo.app.services.ToolRunner
import com.rojo.app.utils.json
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.withContext
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Export feature: bundles a project into a .zip-style app bundle written to
 * [Context.filesDir]/captain_rojo/captain_rojo_<project-id>.zip.
 *
 * Bundle contents:
 *   manifest.json  — export manifest (sources, tool versions, stub notes)
 *   logo.png       — project logo from imageUri, or a placeholder generated
 *                    with logo_gen.py local
 *   ad.mp4         — project ad videoUri (reused; generation is stubbed here)
 *   vo.wav         — voiceover generated by tts_voiceover.py (placeholder)
 *
 * What remains stubbed: signing / AGP bundling, Play Store upload, content://
 * URI resolution, ad-video generation, and real piper synthesis (the TTS
 * tool fails closed when the voice model is missing, so no fake WAV is ever
 * shipped as if it were real).
 */
sealed class ExportResult {
    object Loading : ExportResult()
    data class Success(val bundleUri: String, val manifest: ProjectManifest) : ExportResult()
    data class Error(val message: String) : ExportResult()
}

@kotlinx.serialization.Serializable
data class ProjectManifest(
    val appName: String,
    val projectId: String,
    val projectName: String,
    val logoPath: String?,
    val videoPath: String?,
    val voiceoverPath: String?,
    val exportTime: Long,
    val toolVersions: Map<String, String>,
    val notes: List<String>
)

object ExportFeature {

    /**
     * Starts the bundle build. Collect on an IO dispatcher (e.g. from
     * viewModelScope) so the blocking ProcessBuilder + ZipOutputStream work
     * does not freeze the UI thread.
     */
    fun export(project: Project, context: Context, toolRunner: ToolRunner): Flow<ExportResult> = flow {
        emit(ExportResult.Loading)
        val outcome = withContext(Dispatchers.IO) {
            buildBundle(project, context, toolRunner)
        }
        emit(ExportResult.Success(outcome.uri, outcome.manifest))
    }.catch { e ->
        emit(ExportResult.Error(e.message ?: "Export failed"))
    }
}

private data class BundleOutcome(val uri: String, val manifest: ProjectManifest)

private fun buildBundle(project: Project, context: Context, toolRunner: ToolRunner): BundleOutcome {
    val bundleDir = File(context.filesDir, "captain_rojo").apply { mkdirs() }
    val zipFile = File(bundleDir, "captain_rojo_${project.id}.zip")

    val logoSrc = resolveLogo(project, File(bundleDir, "logo.png"), toolRunner)
        ?: generatePlaceholderLogo(toolRunner, File(bundleDir, "logo.png"))
    val hasProjectLogo = project.logo?.imageUri?.takeIf { it.isNotBlank() }?.startsWith("file://") == true
        && File(project.logo.imageUri.removePrefix("file://")).isFile
    val voSrc = resolveVoiceover(project, File(bundleDir, "vo.wav"), toolRunner)

    val manifest = ProjectManifest(
        appName = "Captain Rojo",
        projectId = project.id,
        projectName = project.name,
        logoPath = logoSrc,
        videoPath = adSrc,
        voiceoverPath = voSrc,
        exportTime = System.currentTimeMillis(),
        toolVersions = toolVersions(toolRunner),
        notes = notes(project, logoSrc, adSrc, voSrc)
    )

    zipFile.parentFile.mkdirs()
    ZipOutputStream(FileOutputStream(zipFile)).use { zos ->
        addTextEntry(zos, "manifest.json", json.encodeToString(ProjectManifest.serializer(), manifest))
        addFileEntry(zos, logoSrc, "logo.png")
        addFileEntry(zos, adSrc, "ad.mp4")
        addFileEntry(zos, voSrc, "vo.wav")
    }

    BundleOutcome(zipFile.path, manifest)
}

private fun resolveLogo(project: Project, dest: File, toolRunner: ToolRunner): String? {
    val uri = project.logo?.imageUri?.takeIf { it.isNotBlank() } ?: return null
    // content:// URIs need a content resolver — stubbed for this prototype.
    return if (uri.startsWith("file://")) {
        val file = File(uri.removePrefix("file://"))
        if (file.isFile) file.path else null
    } else {
        null
    }
}

private fun resolveAd(project: Project, dest: File): String? {
    val uri = project.ad?.videoUri?.takeIf { it.isNotBlank() } ?: return null
    return if (uri.startsWith("file://")) {
        val file = File(uri.removePrefix("file://"))
        if (file.isFile) file.path else null
    } else {
        null
    }
}

private fun resolveVoiceover(project: Project, dest: File, toolRunner: ToolRunner): String? {
    val script = project.ad?.voiceover?.takeIf { it.isNotBlank() } ?: "Welcome to Captain Rojo."
    val result = toolRunner.run(
        "tts_voiceover.py",
        "--script", script,
        "--voice", "en_US-lessons",
        "--output", dest.path
    )
    return if (result.isSuccess) {
        result.getOrDefault(emptyMap())["output"]?.takeIf { it.isNotBlank() }
    } else {
        // Fails closed: never ship a placeholder WAV as if it were real.
        null
    }
}

private fun generatePlaceholderLogo(toolRunner: ToolRunner, dest: File): String {
    val result = toolRunner.run("logo_gen.py", "--tool", "local", "--style", "minimal", "--file_out", dest.path)
    if (result.isFailure) {
        throw IllegalStateException(toolRunner.lastError ?: "placeholder logo generation failed")
    }
    return dest.path
}

private fun toolVersions(toolRunner: ToolRunner): Map<String, String> {
    val result = toolRunner.run("health_check.py")
    return result.getOrDefault(emptyMap()).filterValues { it.isNotBlank() }
}

private fun notes(project: Project, logoSrc: String?, adSrc: String?, voSrc: String?): List<String> = mutableListOf(
    "ZIP bundle only (captain_rojo/<project-id>.zip); signing, AGP bundling and Play Store upload are not done by this feature.",
    "Logo: ${if (hasProjectLogo) "reused imageUri" else "generated placeholder (logo_gen.py local)"}",
    "Ad video: ${if (adSrc == null) "stubbed (project ad has no videoUri)" else "reused ad.videoUri"}",
    "Voiceover: ${if (voSrc == null) "stubbed (piper not installed / synthetic failed)" else "generated by tts_voiceover.py"}",
    "Logo and voiceover are copies of the project sources; ad video is reused, not re-rendered here."
)

private fun addTextEntry(zos: ZipOutputStream, entryName: String, text: String) {
    zos.putNextEntry(ZipEntry(entryName))
    zos.write(text.toByteArray(Charsets.UTF_8))
    zos.closeEntry()
}

private fun addFileEntry(zos: ZipOutputStream, source: String?, entryName: String) {
    val file = source?.let { File(it) } ?: return
    if (!file.isFile) return
    zos.putNextEntry(ZipEntry(entryName))
    FileInputStream(file).use { it.copyTo(zos) }
    zos.closeEntry()
}
